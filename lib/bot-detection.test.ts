import test from 'node:test';
import assert from 'node:assert/strict';
import { isLikelyBotUserAgent, isValidVisitorId } from './bot-detection';

const CHROME_ANDROID =
  'Mozilla/5.0 (Linux; Android 14; SM-S918B) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Mobile Safari/537.36';
const SAFARI_IPHONE =
  'Mozilla/5.0 (iPhone; CPU iPhone OS 17_4 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.4 Mobile/15E148 Safari/604.1';
const DUCKDUCKGO_APP =
  'Mozilla/5.0 (iPhone; CPU iPhone OS 17_4 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.4 Mobile/15E148 DuckDuckGo/7 Safari/605.1.15';

test('real browsers are not treated as bots', () => {
  assert.equal(isLikelyBotUserAgent(CHROME_ANDROID), false);
  assert.equal(isLikelyBotUserAgent(SAFARI_IPHONE), false);
  assert.equal(isLikelyBotUserAgent(DUCKDUCKGO_APP), false);
});

test('crawlers, previews, headless browsers and scripts are bots', () => {
  const bots = [
    'Mozilla/5.0 (compatible; Googlebot/2.1; +http://www.google.com/bot.html)',
    'facebookexternalhit/1.1 (+http://www.facebook.com/externalhit_uatext.php)',
    'WhatsApp/2.23.20.0 A',
    'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) HeadlessChrome/124.0.0.0 Safari/537.36',
    'Mozilla/5.0 (Linux; Android 11; moto g power) Chrome-Lighthouse',
    'python-requests/2.31.0 and some padding',
    'curl/8.4.0 with extra padding here',
    'vercel-screenshot/1.0 additional padding',
  ];
  for (const ua of bots) {
    assert.equal(isLikelyBotUserAgent(ua), true, ua);
  }
});

test('missing or tiny user agents are bots', () => {
  assert.equal(isLikelyBotUserAgent(undefined), true);
  assert.equal(isLikelyBotUserAgent(null), true);
  assert.equal(isLikelyBotUserAgent(''), true);
  assert.equal(isLikelyBotUserAgent('Mozilla/5.0'), true);
});

test('visitor ids must be generated by the tracking client', () => {
  assert.equal(isValidVisitorId('vis-3f2b8c1e-9d4a-4e7b-a1c2-5d6e7f8a9b0c'), true);
  assert.equal(isValidVisitorId('vis-mf3k2a1-x9q2lm4p'), true);
  assert.equal(isValidVisitorId(undefined), false);
  assert.equal(isValidVisitorId(''), false);
  assert.equal(isValidVisitorId('vis-1'), false);
  assert.equal(isValidVisitorId('anything-else-entirely'), false);
  assert.equal(isValidVisitorId('vis-<script>alert(1)</script>'), false);
});
