/**
 * Helpers that decide whether an analytics request should be counted at all.
 * Shared by the API route (server) and the tracking client (browser).
 */

// Crawlers, link-preview fetchers, uptime monitors, headless browsers and HTTP libraries.
const BOT_UA_PATTERN = new RegExp(
  [
    'bot',
    'crawl',
    'spider',
    'slurp',
    'slack-',
    'scrape',
    'headless',
    'phantomjs',
    'puppeteer',
    'playwright',
    'selenium',
    'webdriver',
    'lighthouse',
    'pagespeed',
    'gtmetrix',
    'pingdom',
    'uptime',
    'monitor',
    'scanner',
    'preview',
    'facebookexternalhit',
    '^whatsapp',
    'embedly',
    'quora link',
    'vercel',
    'curl/',
    'wget/',
    'python-requests',
    'python-urllib',
    'aiohttp',
    'httpx',
    'go-http-client',
    'java/',
    'libwww',
    'node-fetch',
    'undici',
    'axios',
    'okhttp/',
    'postmanruntime',
    'insomnia',
    'ahrefs',
    'semrush',
    'mj12',
    'dotbot',
    'chrome-lighthouse',
    'google-read-aloud',
    'google-inspectiontool',
    'apis-google',
  ].join('|'),
  'i'
);

export function isLikelyBotUserAgent(userAgent?: string | null): boolean {
  if (!userAgent) return true;
  const ua = userAgent.trim();
  // Real browsers always send a long UA string. Anything this short is a script.
  if (ua.length < 20) return true;
  return BOT_UA_PATTERN.test(ua);
}

/** Visitor ids are generated by the tracking client. Anything else is rejected. */
const VISITOR_ID_PATTERN = /^vis-[a-z0-9-]{8,60}$/;

export function isValidVisitorId(value: unknown): value is string {
  return typeof value === 'string' && VISITOR_ID_PATTERN.test(value);
}

/** Name of the cookie that marks a browser as "admin device, never count". */
export const IGNORE_DEVICE_COOKIE = 'openframe_ignore';
